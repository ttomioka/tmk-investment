package jp.tmkworks.tmk_investment.util.jooq.generator;

import org.jooq.codegen.DefaultGeneratorStrategy;
import org.jooq.meta.Definition;

public class CustomGeneratorStrategy extends DefaultGeneratorStrategy {

  @Override
  public String getFileHeader(Definition definition, Mode mode) {
    return "This file is generated by tmkworks.";
  }
  
  @Override
  public String getJavaMemberName(Definition definition, Mode mode) {
      var name = super.getJavaMemberName(definition, mode);
      var replaced = replace(name);
      return replaced;
  }

  @Override
  public String getJavaGetterName(Definition definition, Mode mode) {
      var name = super.getJavaGetterName(definition, mode);
      var replaced = replace(name);
      return replaced;
  }

  @Override
  public String getJavaSetterName(Definition definition, Mode mode) {
      var name = super.getJavaSetterName(definition, mode);
      var replaced = replace(name);
      return replaced;
  }
  
  
  public String replace(String original) {
    var replaced = original;
    replaced = original.replaceAll("id$", "ID");
    replaced = replaced.replaceAll("^tr$", "TR");
    replaced = replaced.replaceAll("^Tr$", "TR");
    replaced = replaced.replaceAll("^タートルn$", "タートルN");
    replaced = replaced.replaceAll("^n値$", "N値");
    replaced = replaced.replaceAll("bo", "BO");
    replaced = replaced.replaceAll("atr", "ATR");
    return replaced;
  }
  
  
}
